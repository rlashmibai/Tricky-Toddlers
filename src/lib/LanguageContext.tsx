// Protect brand terms in text nodes by wrapping them in <span class="notranslate" translate="no">
const BRAND_REGEX = /(\bTricky\s+Toddlers\b|\bTricky\s+Toddler\b|\bFoodLens\s+AI\b|\bFoodLens\s+Pro\b|\bAI\s+NutriChef\b|\bNutriBand\b)/g;

function protectBrandNamesInDOM(root: Node = document.body) {
  if (!root || typeof document === 'undefined') return;

  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const textNodes: Text[] = [];
  let current = walker.nextNode();
  while (current) {
    textNodes.push(current as Text);
    current = walker.nextNode();
  }

  for (const textNode of textNodes) {
    const parent = textNode.parentElement;
    if (!parent) continue;
    const tag = parent.tagName.toLowerCase();
    if (tag === 'script' || tag === 'style' || tag === 'textarea' || tag === 'input' || tag === 'noscript') {
      continue;
    }

    let val = textNode.nodeValue || '';
    if (!val.trim()) continue;

    // 1. Scrub any literal Google Translate mistranslations of "Tricky Toddlers"
    let scrubbed = val;
    for (const rule of LITERAL_BRAND_MISTRANSLATIONS) {
      if (rule.pattern.test(scrubbed)) {
        scrubbed = scrubbed.replace(rule.pattern, rule.replacement);
      }
    }
    if (scrubbed !== val) {
      textNode.nodeValue = scrubbed;
      val = scrubbed;
    }

    // 2. If already inside a .notranslate element, no need to split
    if (parent.closest('.notranslate, [translate="no"]')) {
      continue;
    }

    // 3. Wrap brand names in <span class="notranslate" translate="no"> so Google Translate keeps them as brand names while translating the sentence context naturally
    if (BRAND_REGEX.test(val)) {
      BRAND_REGEX.lastIndex = 0;
      const parts = val.split(BRAND_REGEX);
      if (parts.length > 1) {
        const frag = document.createDocumentFragment();
        for (const part of parts) {
          if (!part) continue;
          if (BRAND_REGEX.test(part)) {
            const span = document.createElement('span');
            span.className = 'notranslate';
            span.setAttribute('translate', 'no');
            span.textContent = part;
            frag.appendChild(span);
          } else {
            frag.appendChild(document.createTextNode(part));
          }
          BRAND_REGEX.lastIndex = 0;
        }
        parent.replaceChild(frag, textNode);
      }
    }
  }
}

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<LanguageCode>(() => {
    const saved = localStorage.getItem('app_language');
    return (saved as LanguageCode) || 'en';
  });

  const triggerGoogleTranslate = (langCode: LanguageCode) => {
    try {
      // Ensure all brand names are protected before triggering translation
      protectBrandNamesInDOM(document.body);

      const domain = window.location.hostname;
      if (langCode === 'en') {
        document.cookie = `googtrans=; expires=Thu, 01 Jan 1970 00:00:00 UTC; path=/;`;
        document.cookie = `googtrans=; expires=Thu, 01 Jan 1970 00:00:00 UTC; path=/; domain=.${domain};`;
        document.cookie = `googtrans=; expires=Thu, 01 Jan 1970 00:00:00 UTC; path=/; domain=${domain};`;
      } else {
        document.cookie = `googtrans=/en/${langCode}; path=/;`;
        document.cookie = `googtrans=/en/${langCode}; path=/; domain=.${domain};`;
        document.cookie = `googtrans=/en/${langCode}; path=/; domain=${domain};`;
      }

      const selectEl = document.querySelector('.goog-te-combo') as HTMLSelectElement | null;
      if (selectEl) {
        selectEl.value = langCode;
        selectEl.dispatchEvent(new Event('change'));
      } else if (langCode !== 'en') {
        let attempts = 0;
        const interval = setInterval(() => {
          attempts++;
          protectBrandNamesInDOM(document.body);
          const el = document.querySelector('.goog-te-combo') as HTMLSelectElement | null;
          if (el) {
            el.value = langCode;
            el.dispatchEvent(new Event('change'));
            clearInterval(interval);
          } else if (attempts > 20) {
            clearInterval(interval);
          }
        }, 300);
      }
    } catch (err) {
      console.warn('Language translation trigger warning:', err);
    }
  };

  // Continuous DOM guardian to protect "Tricky Toddlers" across route changes and dynamic renders
  useEffect(() => {
    protectBrandNamesInDOM(document.body);

    let rafId: number | null = null;
    const observer = new MutationObserver(() => {
      if (rafId) cancelAnimationFrame(rafId);
      rafId = requestAnimationFrame(() => {
        protectBrandNamesInDOM(document.body);
      });
    });

    observer.observe(document.body, {
      childList: true,
      subtree: true,
      characterData: true,
    });

    return () => {
      if (rafId) cancelAnimationFrame(rafId);
      observer.disconnect();
    };
  }, []);

  useEffect(() => {
    localStorage.setItem('app_language', language);
    document.documentElement.lang = language;
    triggerGoogleTranslate(language);
  }, [language]);

  const setLanguage = (lang: LanguageCode | string) => {
    const validCode = (SUPPORTED_LANGUAGES.find(l => l.code === lang || l.name.toLowerCase() === String(lang).toLowerCase())?.code || 'en') as LanguageCode;
    setLanguageState(validCode);
    localStorage.setItem('app_language', validCode);
    triggerGoogleTranslate(validCode);
  };

  const t = (key: string): string => {
    return translations[language]?.[key] || translations['en']?.[key] || formatKeyFallback(key);
  };

  const getAIPromptModifier = (): string => {
    if (language === 'en') return '';
    const langInfo = SUPPORTED_LANGUAGES.find(l => l.code === language);
    return `\n\nIMPORTANT LANGUAGE INSTRUCTION: Please respond entirely in ${langInfo?.name} (${langInfo?.localName}) with natural, warm, contextually accurate phrasing. Do NOT translate the brand name "Tricky Toddlers" literally; always keep "Tricky Toddlers" as "Tricky Toddlers".`;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t, getAIPromptModifier }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);
