interface LanguageContextType {
  language: string;
  setLanguage: (code: string) => Promise<void>;
  t: (key: string) => string;
  getAIPromptModifier: () => string;
}

const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

// Helper function to trigger Google Translate on the whole web page
const triggerGoogleTranslate = (targetCode: string) => {
  if (typeof window === 'undefined' || typeof document === 'undefined') return;

  const setCookie = (name: string, val: string) => {
    document.cookie = `${name}=${val}; path=/;`;
    const host = window.location.hostname;
    document.cookie = `${name}=${val}; path=/; domain=${host};`;
  };

  const clearCookie = (name: string) => {
    document.cookie = `${name}=; path=/; expires=Thu, 01 Jan 1970 00:00:00 UTC;`;
    const host = window.location.hostname;
    document.cookie = `${name}=; path=/; domain=${host}; expires=Thu, 01 Jan 1970 00:00:00 UTC;`;
  };

  if (targetCode === 'en') {
    clearCookie('googtrans');
    const select = document.querySelector('.goog-te-combo') as HTMLSelectElement | null;
    if (select) {
      select.value = 'en';
      select.dispatchEvent(new Event('change', { bubbles: true }));
    }
  } else {
    setCookie('googtrans', `/en/${targetCode}`);
    const select = document.querySelector('.goog-te-combo') as HTMLSelectElement | null;
    if (select) {
      select.value = targetCode;
      select.dispatchEvent(new Event('change', { bubbles: true }));
    } else {
      setTimeout(() => {
        const retrySelect = document.querySelector('.goog-te-combo') as HTMLSelectElement | null;
        if (retrySelect) {
          retrySelect.value = targetCode;
          retrySelect.dispatchEvent(new Event('change', { bubbles: true }));
        }
      }, 500);
    }
  }
};

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const { user, profile, refreshProfile } = useAuth();
  const [language, setLanguageState] = useState<string>(() => {
    return localStorage.getItem('preferred_language') || 'en';
  });

  // Sync with user profile on Firestore if they log in and have a language set
  useEffect(() => {
    if (profile?.language && profile.language !== language) {
      setLanguageState(profile.language);
      localStorage.setItem('preferred_language', profile.language);
      triggerGoogleTranslate(profile.language);
    }
  }, [profile]);

  // Activate Google Translate on initial load if user has preferred non-English
  useEffect(() => {
    if (language && language !== 'en') {
      triggerGoogleTranslate(language);
      const timer = setTimeout(() => {
        triggerGoogleTranslate(language);
      }, 800);
      return () => clearTimeout(timer);
    }
  }, []);

  const setLanguage = async (code: string) => {
    setLanguageState(code);
    localStorage.setItem('preferred_language', code);
    triggerGoogleTranslate(code);
    
    // Also save to user profile if logged in
    if (user && db) {
      try {
        const { doc, updateDoc } = await import('firebase/firestore');
        const userRef = doc(db, 'users', user.uid);
        await updateDoc(userRef, {
          language: code,
        });
        await refreshProfile();
      } catch (err) {
        console.error("Error updating user language on firestore:", err);
      }
    }
  };

  const t = (key: string): string => {
    const langDict = translations[language] || translations['en'];
    return langDict[key] || translations['en'][key] || key;
  };

  // Construct instruction for Gemini prompt
  const getAIPromptModifier = (): string => {
    if (language === 'en') return '';
    const selectedLangObj = SUPPORTED_LANGUAGES.find(l => l.code === language);
    if (!selectedLangObj) return '';
    
    return `CRITICAL LANGUAGE REQUIREMENT: The user has selected the language: ${selectedLangObj.name} (${selectedLangObj.localName}). You MUST write your ENTIRE response, including ALL markdown headings, lists, 5 scripts, and guidance, purely in ${selectedLangObj.name} (${selectedLangObj.localName}) using its native script! Translate the 5 script quotes into authentic spoken ${selectedLangObj.name}. Never revert to English.`;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t, getAIPromptModifier }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (context === undefined) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};
